export function getContentStudioMediaLibrary(functionId: ContentStudioFunctionId): ContentStudioMediaAsset[] {
  return MEDIA_LIBRARY.filter((asset) => asset.functionId === functionId);
}

export function contentStudioMediaKindLabel(kind: ContentStudioMediaAsset["kind"]): string {
  if (kind === "image") return "Image";
  if (kind === "video") return "Video";
  if (kind === "document") return "Document";
  if (kind === "logo") return "Logo";
  return "Deck";
}
