function gtVideoTests(
  entries: Array<{
    slug: string;
    top1Summary: string;
    runRef: string;
    comments?: string;
  }>,
): WolfModelTestingRecord["videoTests"] {
  return entries.map((entry) => ({
    videoSlug: entry.slug,
    outcome: "TESTED",
    testStatus: "TESTED",
    confidenceSummary: entry.top1Summary,
    detectionCount: "Mission 1 GT benchmark",
    uniqueAnimalCount: "Mission 1 GT benchmark",
    benchmarkRunReference: entry.runRef,
    testedAt: "2026-09-06",
    comments: entry.comments ?? "",
    evidence: [],
  }));
}

const ANIMALS_SLUG = "animals";

function evidenceNote(repositoryPath: string, label: string): ModelTestingEvidenceImage {
  return {
    kind: "detector_output",
    label,
    url: null,
    repositoryPath,
  };
}

function animalsOnlyVideoTests(
  modelId: string,
  outcome: WolfModelTestingRecord["outcome"],
  testStatus: WolfModelTestingRecord["testStatus"],
  summary: string,
  comments: string,
  evidence: ModelTestingEvidenceImage[],
  testedAt: string | null = null,
): WolfModelTestingRecord["videoTests"] {
  return [
    {
      videoSlug: ANIMALS_SLUG,
      outcome,
      testStatus,
      confidenceSummary: summary,
      detectionCount: "Not yet benchmarked",
      uniqueAnimalCount: "Not yet benchmarked",
      benchmarkRunReference: null,
      testedAt,
      comments,
      evidence,
    },
  ];
}

