function ratedResponses(scores: number[]) {
  return blankQuestionResponses().map((item, index) => ({
    ...item,
    rating: (scores[index] ?? 4) as 1 | 2 | 3 | 4 | 5,
    managerComments: index % 6 === 0 ? "Consistently strong contribution." : "",
    employeeComments: index % 8 === 0 ? "Agreed — focus area for next cycle." : "",
  }));
}

function competencies(scores: number[], prefix: string) {
  return blankCompetencyScores().map((item, index) => ({
    ...item,
    id: `${prefix}-${index}`,
    score: (scores[index] ?? 4) as 1 | 2 | 3 | 4 | 5,
    notes: index === 0 ? "Key strength for ABHI members" : "",
  }));
}

